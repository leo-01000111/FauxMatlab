"""
MATLAB's binary live script, ``.mlx``.

An ``.mlx`` is an Open Packaging Conventions zip. ``matlab/document.xml`` is
WordprocessingML: one ``<w:p>`` per paragraph, its ``w:pStyle`` saying what it
is — ``title``, ``heading``, ``text``, ``code`` — and code held as CDATA. What
was learnt from real files (the SiPro labs in ``tests/fixtures/sipro``, saved
by R2023a, and a public example with equations and nested headings):

* A paragraph whose ``w:pPr`` holds ``<w:sectPr/>`` is a **section break**.
* Headings below level 1 are wrapped for older readers::

      <mc:AlternateContent><mc:Choice Requires="R2018b">
        <w:pPr><w:pStyle w:val="heading2"/>…</w:pPr>
      </mc:Choice><mc:Fallback>…heading…</mc:Fallback></mc:AlternateContent>

* **Equations** are LaTeX, not MathML or OMML::

      <w:customXml w:element="equation">
        <w:customXmlPr><w:attr w:name="displayStyle" w:val="false"/></w:customXmlPr>
        <w:r><w:t>z=x^2+y^2</w:t></w:r>
      </w:customXml>

  ``displayStyle="true"`` is a display equation.
* Links are ``<w:hyperlink w:docLocation="url">``; bold, italic and
  underline are the usual ``w:rPr`` flags.

``matlab/output.xml`` holds the outputs of the last run in MATLAB; it is not
read — outputs are regenerated by running the cells here.

The writer produces the same structure. It has **not** been checked against
a real MATLAB, which is not available where this was written.
"""

from __future__ import annotations

import uuid
import zipfile
from datetime import UTC, datetime
from pathlib import Path
from xml.etree import ElementTree as ET
from xml.sax.saxutils import escape, quoteattr

from .document import Cell, CellKind, LiveDocument
from .markup import Node, escape_markdown, parse_blocks, parse_inline

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
MC = "{http://schemas.openxmlformats.org/markup-compatibility/2006}"

_HEADINGS = {"title": CellKind.TITLE, "heading": CellKind.HEADING,
             "heading1": CellKind.HEADING, "heading2": CellKind.HEADING2,
             "heading3": CellKind.HEADING3}


class MlxError(ValueError):
    """Not a live script, or one this reader cannot make sense of."""


# ──────────────────────────────────────────────────────────────
#  Reading
# ──────────────────────────────────────────────────────────────

def read_mlx(path: str | Path) -> LiveDocument:
    path = Path(path)
    try:
        with zipfile.ZipFile(path) as archive:
            xml = archive.read("matlab/document.xml")
    except (zipfile.BadZipFile, KeyError) as exc:
        raise MlxError(f"{path.name} is not a MATLAB live script "
                       f"({exc})") from exc
    return LiveDocument(parse_document_xml(xml), path)


def parse_document_xml(xml: bytes | str) -> list[Cell]:
    """The cells of a ``document.xml``."""
    try:
        root = ET.fromstring(xml)
    except ET.ParseError as exc:
        raise MlxError(f"document.xml does not parse: {exc}") from exc
    body = root.find(f"{W}body")
    if body is None:
        raise MlxError("document.xml has no body")

    cells: list[Cell] = []
    pending_break = False
    for p in body.findall(f"{W}p"):
        ppr = _paragraph_properties(p)
        if ppr is not None and ppr.find(f"{W}sectPr") is not None:
            pending_break = bool(cells)
            continue
        style_el = ppr.find(f"{W}pStyle") if ppr is not None else None
        style = style_el.get(f"{W}val", "text") if style_el is not None \
            else "text"

        if style == "code":
            source = "".join(t.text or "" for t in p.iter(f"{W}t"))
            source = source.replace("\r\n", "\n").rstrip()
            cells.append(Cell.code(source, section_break=pending_break))
        elif style in _HEADINGS:
            text = _runs_markdown(p).strip()
            cells.append(Cell.text(text, _HEADINGS[style],
                                   section_break=pending_break))
        else:
            text = _runs_markdown(p).strip()
            if not text:
                continue
            listed = style.lower().startswith("list") or \
                p.find(f".//{W}numPr") is not None
            if listed:
                text = "- " + text
            previous = cells[-1] if cells else None
            if (previous is not None and previous.kind is CellKind.TEXT
                    and not pending_break):
                both_listed = listed and previous.source.splitlines()[-1] \
                    .startswith("- ")
                previous.source += ("\n" if both_listed else "\n\n") + text
                continue
            cells.append(Cell.text(text, section_break=pending_break))
        pending_break = False
    return cells


def _paragraph_properties(p):
    ppr = p.find(f"{W}pPr")
    if ppr is not None:
        return ppr
    # Newer styles hide inside mc:AlternateContent — take the Choice.
    choice = p.find(f"{MC}AlternateContent/{MC}Choice")
    if choice is not None:
        return choice.find(f"{W}pPr")
    return None


def _runs_markdown(p) -> str:
    """A paragraph's runs, equations and links as text-cell markup."""
    parts: list[str] = []
    for child in p:
        tag = child.tag
        if tag == f"{W}r":
            parts.append(_run_markdown(child))
        elif tag == f"{W}hyperlink":
            text = "".join(_run_markdown(r) for r in child.iter(f"{W}r"))
            url = child.get(f"{W}docLocation") or ""
            parts.append(f"[{text}]({url})" if url else text)
        elif tag == f"{W}customXml" and child.get(f"{W}element") == "equation":
            latex = "".join(t.text or "" for t in child.iter(f"{W}t")).strip()
            display = any(
                a.get(f"{W}name") == "displayStyle"
                and a.get(f"{W}val") == "true"
                for a in child.iter(f"{W}attr"))
            parts.append(f"$${latex}$$" if display else f"${latex}$")
    # A display equation alone in its paragraph reads back as a $$ block.
    return "".join(parts)


def _run_markdown(r) -> str:
    text = "".join((t.text or "") if t.tag == f"{W}t" else " "
                   for t in r if t.tag in (f"{W}t", f"{W}br", f"{W}tab"))
    if not text:
        return ""
    body = escape_markdown(text)
    rpr = r.find(f"{W}rPr")
    if rpr is None or not body.strip():
        return body
    lead = body[:len(body) - len(body.lstrip())]
    trail = body[len(body.rstrip()):]
    core = body.strip()
    if _flag(rpr, "u"):
        core = f"<u>{core}</u>"
    if _flag(rpr, "i"):
        core = f"*{core}*"
    if _flag(rpr, "b"):
        core = f"**{core}**"
    return lead + core + trail


def _flag(rpr, name: str) -> bool:
    el = rpr.find(f"{W}{name}")
    return el is not None and el.get(f"{W}val", "true") not in (
        "false", "0", "none")


# ──────────────────────────────────────────────────────────────
#  Writing
# ──────────────────────────────────────────────────────────────

_NS = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
_MC = 'xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"'


def write_mlx(document: LiveDocument, path: str | Path,
              release: str = "R2023a") -> Path:
    """
    Write an ``.mlx``: the document, an empty output part, and the metadata
    MATLAB writes. Modelled on files saved by R2023a.
    """
    path = Path(path)
    now = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    parts = {
        "[Content_Types].xml": _CONTENT_TYPES,
        "_rels/.rels": _RELS,
        "matlab/document.xml": document_xml(document),
        "matlab/output.xml": _OUTPUT,
        "metadata/coreProperties.xml": _CORE.format(now=now),
        "metadata/mwcoreProperties.xml": _MWCORE.format(release=release),
        "metadata/mwcorePropertiesExtension.xml":
            _MWEXT.format(uuid=uuid.uuid4()),
        "metadata/mwcorePropertiesReleaseInfo.xml":
            _RELEASE.format(release=release),
    }
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, text in parts.items():
            archive.writestr(name, text.encode("utf-8"))
    return path


def document_xml(document: LiveDocument) -> str:
    out = ['<?xml version="1.0" encoding="UTF-8"?>'
           f"<w:document {_NS}><w:body>"]
    for cell in document.cells:
        if cell.section_break:
            out.append("<w:p><w:pPr><w:sectPr/></w:pPr></w:p>")
        if cell.is_code:
            out.append('<w:p><w:pPr><w:pStyle w:val="code"/></w:pPr>'
                       f"<w:r><w:t>{_cdata(cell.source.rstrip())}</w:t></w:r>"
                       "</w:p>")
        elif cell.kind.is_heading:
            runs = _runs_xml(parse_inline(" ".join(cell.source.split())))
            out.append(f"<w:p>{_heading_ppr(cell.kind)}{runs}</w:p>")
        else:
            out.extend(_text_paragraphs(cell.source))
    out.append("</w:body></w:document>")
    return "".join(out)


def _ppr(style: str) -> str:
    return (f'<w:pPr><w:pStyle w:val="{style}"/><w:jc w:val="left"/>'
            "</w:pPr>")


def _heading_ppr(kind: CellKind) -> str:
    if kind in (CellKind.TITLE, CellKind.HEADING):
        return _ppr(kind.value)
    return (f'<mc:AlternateContent {_MC}><mc:Choice Requires="R2018b">'
            f"{_ppr(kind.value)}</mc:Choice><mc:Fallback>{_ppr('heading')}"
            "</mc:Fallback></mc:AlternateContent>")


def _text_paragraphs(source: str) -> list[str]:
    out = []
    for block in parse_blocks(source):
        if block.kind == "math":
            out.append(f"<w:p>{_ppr('text')}{_equation(block.math, True)}"
                       "</w:p>")
        elif block.kind in ("ul", "ol"):
            for n, item in enumerate(block.items, 1):
                mark = "• " if block.kind == "ul" else f"{n}. "
                out.append(f"<w:p>{_ppr('text')}{_run(mark)}"
                           f"{_runs_xml(item)}</w:p>")
        else:
            out.append(f"<w:p>{_ppr('text')}{_runs_xml(block.nodes)}</w:p>")
    return out


def _runs_xml(nodes: list[Node], flags: frozenset = frozenset()) -> str:
    out = []
    for n in nodes:
        if n.kind in ("text", "code"):
            out.append(_run(n.text, flags))
        elif n.kind == "interp":
            out.append(_run("{{" + n.text + "}}", flags))
        elif n.kind == "math":
            out.append(_equation(n.text, n.display))
        elif n.kind == "link":
            out.append(f"<w:hyperlink w:docLocation={quoteattr(n.url)}>"
                       f"{_runs_xml(n.children, flags)}</w:hyperlink>")
        else:
            flag = {"bold": "b", "italic": "i", "underline": "u"}[n.kind]
            out.append(_runs_xml(n.children, flags | {flag}))
    return "".join(out)


def _run(text: str, flags: frozenset = frozenset()) -> str:
    if not text:
        return ""
    rpr = "".join(f"<w:{f}/>" for f in ("b", "i") if f in flags)
    if "u" in flags:
        rpr += '<w:u w:val="single"/>'
    rpr = f"<w:rPr>{rpr}</w:rPr>" if rpr else ""
    return f"<w:r>{rpr}<w:t>{escape(text)}</w:t></w:r>"


def _equation(latex: str, display: bool) -> str:
    style = "true" if display else "false"
    return ('<w:customXml w:element="equation"><w:customXmlPr>'
            f'<w:attr w:name="displayStyle" w:val="{style}"/>'
            f"</w:customXmlPr><w:r><w:t>{escape(latex)}</w:t></w:r>"
            "</w:customXml>")


def _cdata(text: str) -> str:
    return "<![CDATA[" + text.replace("]]>", "]]]]><![CDATA[>") + "]]>"


